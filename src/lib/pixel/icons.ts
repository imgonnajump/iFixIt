export type IconName = keyof typeof ICONS;

export function drawIcon(ctx: CanvasRenderingContext2D, name: IconName, x = 0, y = 0, scale = 1) {
  const rows = ICONS[name];
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const c = ICON_PALETTE[row[i]];
      if (!c) continue;
      ctx.fillStyle = c;
      ctx.fillRect(x + i * scale, y + j * scale, scale, scale);
    }
  });
}
